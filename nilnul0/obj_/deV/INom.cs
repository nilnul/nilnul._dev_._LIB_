    /// 第一层哲理，是“命名即分类，分类即理解”。当一个对象无法被恰当命名时，它往往也还没有被真正理解。很多初学者写程序或写数据库脚本时，喜欢用含糊、随意、临时的名字，因为那样最省事。但省事的代价，是对象之间的边界逐渐模糊，最终谁也说不清一个文件、一个表、一个脚本、一个目录究竟承担什么责任。
    /// nilnul的命名体系则反其道而行之，它宁可显得生硬，也要尽量把对象的归属关系表现出来。这种做法提醒我们：所谓“理解”，并不是脑中朦胧知道大概，而是能够把对象放进一个稳定的分类框架里。
    /// 
    ///  “名称与实质应尽量一致”。nilnul的命名方式虽然有时看起来不符合流行审美，却始终在追求一种名实对应。`_DB_` 就是数据库对象层，`_SQL_` 就是操作脚本层，`rite_` 指向写操作，`attr` 指向属性，`backup`、`restore` 指向数据库状态管理。
    ///  这种名实对应的追求，实际上是一种反对含糊、反对漂浮的态度。今天的软件世界中，很多名词被包装得过度漂亮，却很难对应清楚的职责和边界。相较之下，nilnul中的命名更像是在提醒我们：不要让语言脱离对象本身，不要让标签变成遮蔽认识的烟幕。名称若能贴近结构，思考就更容易落地；名称若背离结构，系统就会在语言层面先一步走向混乱。
